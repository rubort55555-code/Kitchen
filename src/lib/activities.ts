const BY_CODE = new Map<string, Activity>();
for (const a of ACTIVITIES) if (!BY_CODE.has(a.c)) BY_CODE.set(a.c, a);
/** Занятие по коду (если код повторяется — первое). */
export const actByCode = (c: string): Activity | undefined => BY_CODE.get(c);

/** Ключ занятия: код + название (код 07040 используется и для «стою в очереди», и для «еду стоя»). */
export const actKey = (a: Activity) => a.c + ":" + a.n;
const BY_KEY = new Map(ACTIVITIES.map((a) => [actKey(a), a]));
export const actByKey = (k: string): Activity | undefined => BY_KEY.get(k) || BY_CODE.get(k.split(":")[0]);

/** Поиск по словам названия. */
export function searchActs(q: string, limit = 40): Activity[] {
  const words = q.toLowerCase().replace(/ё/g, "е").split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const res: [number, Activity][] = [];
  for (const a of ACTIVITIES) {
    const n = a.n.toLowerCase().replace(/ё/g, "е");
    if (!words.every((w) => n.includes(w.slice(0, Math.max(3, w.length - 2))))) continue;
    res.push([(n.startsWith(words[0]) ? 0 : 1), a]);
  }
  return res.sort((x, y) => x[0] - y[0]).slice(0, limit).map((x) => x[1]);
}
