/** Заменяет встроенный справочник более новым с сайта: приложение из магазина обновляет справочник без новой версии. */
export function setCatalog(items: CatalogItem[]) {
  if (!Array.isArray(items) || !items.length) return;
  CATALOG.splice(0, CATALOG.length, ...items);
  indexes.clear();
  CATEGORIES.splice(0, CATEGORIES.length, ...new Set(CATALOG.map((x) => x.c)));
}

/** Все продукты: встроенные + добавленные вручную. */
export function allCatalog(custom: CatalogItem[]): CatalogItem[] {
  const own = new Set(custom.map((x) => norm(x.n)));
  return custom.concat(CATALOG.filter((x) => !own.has(norm(x.n))));
}

interface CatIndex { exact: Map<string, CatalogItem>; syn: Map<string, CatalogItem>; stems: Map<string, { it: CatalogItem; re: RegExp; len: number }[]>; memo: Map<string, CatalogItem | null>; words: Map<string, { it: CatalogItem; toks: string[]; len: number }[]> }
const indexes = new Map<string, CatIndex>();

/** Индекс справочника: регулярные выражения собираем один раз (раньше — на каждый вызов, это тормозило). */
function indexFor(custom: CatalogItem[]): CatIndex {
  const sig = custom.map((c) => c.n + "\u0001" + (c.s || []).join(",")).join("|");
  let ix = indexes.get(sig);
  if (ix) return ix;
  ix = { exact: new Map(), syn: new Map(), stems: new Map(), memo: new Map(), words: new Map() };
  const list = allCatalog(custom);
  for (const it of list) { const n = norm(it.n); if (!ix.exact.has(n)) ix.exact.set(n, it); }
  for (const it of list) for (const s of it.s || []) { const n = norm(s); if (!ix.syn.has(n)) ix.syn.set(n, it); }
  for (const it of list) {
    for (const key of [it.n, ...(it.s || [])]) {
      const k = norm(key);
      const stem = k.length > 5 ? k.slice(0, k.length - 1) : k;
      // Короткие основы («сыр», «лук», «рис») — только сами слова с окончанием, иначе «сырники» → сыр.
      const tail = stem.length <= 4 ? "[а-я]{0,3}(?![а-я])" : "";
      const b = stem.slice(0, 2);
      const arr = ix.stems.get(b) || [];
      arr.push({ it, re: new RegExp("(^|[^а-яa-z])" + escapeRe(stem) + tail), len: stem.length });
      ix.stems.set(b, arr);
    }
  }
  // Слова в другом порядке: «сердце куриное» = «куриное сердце»
  for (const it of list) {
    for (const key of [it.n, ...(it.s || [])]) {
      const toks = wordStems(norm(key));
      if (toks.length < 2 || toks.length > 3) continue;
      const e = { it, toks, len: toks.reduce((a, t) => a + t.length, 0) };
      for (const t of new Set(toks.map((x) => x.slice(0, 2)))) {
        const arr = ix.words.get(t) || [];
        arr.push(e);
        ix.words.set(t, arr);
      }
    }
  }
  if (indexes.size > 20) indexes.clear();
  indexes.set(sig, ix);
  return ix;
}

/** Ищет продукт справочника по названию (точно, по синониму или по началу слова). */
export function findCatalog(name: string, custom: CatalogItem[] = []): CatalogItem | null {
  const q = norm(name);
  if (!q) return null;
  const ix = indexFor(custom);
  if (ix.memo.has(q)) return ix.memo.get(q)!;
  let res: CatalogItem | null = ix.exact.get(q) || ix.syn.get(q) || null;
  if (!res) {
    // Начало слова: «помидоры черри» → Помидоры; «филе трески» → Треска
    let bestLen = 0;
    // Берём только основы, начинающиеся так же, как какое-то слово запроса (ускоряет поиск в разы)
    for (const w of q.split(/[^а-яa-z]+/)) {
      const bucket = w.length >= 2 ? ix.stems.get(w.slice(0, 2)) : undefined;
      if (bucket) for (const st of bucket) if (st.len > bestLen && st.re.test(q)) { res = st.it; bestLen = st.len; }
    }
  }
  if (!res) {
    const qw = q.split(/[^а-яa-z0-9]+/).filter(Boolean);
    let best = 0;
    const seen = new Set<unknown>();
    for (const w of qw) {
      for (const e of ix.words.get(w.slice(0, 2)) || []) {
        if (seen.has(e)) continue;
        seen.add(e);
        if (e.len > best && e.toks.every((t) => qw.some((x) => x.startsWith(t)))) { res = e.it; best = e.len; }
      }
    }
  }
  if (ix.memo.size > 5000) ix.memo.clear();
  ix.memo.set(q, res);
  return res;
}

/** Основы слов названия (без окончаний), для поиска при другом порядке слов. */
const wordStems = (k: string) => k.split(/[^а-яa-z0-9]+/).filter((w) => w.length > 2).map((w) => (w.length > 5 ? w.slice(0, w.length - 2) : w.length > 3 ? w.slice(0, w.length - 1) : w));

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** Подсказки при вводе названия. */
export function suggest(query: string, custom: CatalogItem[], frequent: string[], limit = 8): CatalogItem[] {
  const q = norm(query);
  const list = allCatalog(custom);
  if (!q) {
    const byName = new Map(list.map((x) => [norm(x.n), x]));
    return frequent.map((n) => byName.get(norm(n)) || ({ n, c: "Другое", e: "🛒", u: "шт", p: F, d: [5, null, null] } as CatalogItem)).slice(0, limit);
  }
  const scored: [number, CatalogItem][] = [];
  for (const it of list) {
    const n = norm(it.n);
    let sc = -1;
    if (n.startsWith(q)) sc = 3;
    else if (n.includes(q)) sc = 2;
    else if ((it.s || []).some((s) => norm(s).startsWith(q))) sc = 1;
    if (sc >= 0) {
      const fi = frequent.findIndex((f) => norm(f) === n);
      scored.push([sc * 100 + (fi >= 0 ? 50 - Math.min(fi, 49) : 0), it]);
    }
  }
  return scored.sort((a, b) => b[0] - a[0]).slice(0, limit).map((x) => x[1]);
}

/** Срок хранения в днях для места; null — так обычно не хранят. 0 — срок не важен. */
export function shelfDays(it: CatalogItem | null, place: Place): number | null | undefined {
  if (!it) return undefined;
  const i = place === "Холодильник" ? 0 : place === "Морозилка" ? 1 : 2;
  return it.d[i];
}

