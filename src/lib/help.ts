/** Поиск по справке: считаем совпавшие слова в заголовке, ключах и тексте. */
export function searchHelp(q: string): HelpSection[] {
  const words = q.toLowerCase().replace(/ё/g, "е").split(/[^а-яa-z0-9]+/).filter((w) => w.length > 2);
  if (!words.length) return [];
  const all = SECTIONS.concat(FAQ);
  return all
    .map((s) => {
      const hay = (s.title + " " + s.keys + " " + s.text.join(" ")).toLowerCase().replace(/ё/g, "е");
      const score = words.reduce((a, w) => a + (hay.includes(w.slice(0, Math.max(3, w.length - 2))) ? 1 : 0) + (s.keys.includes(w.slice(0, Math.max(3, w.length - 2))) ? 1 : 0), 0);
      return { s, score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 4)
    .map((x) => x.s);
}
