// Кухня рецепта (русская, кавказская, итальянская…) — определяется по названию, меткам и продуктам.
// Свой выбор можно задать в рецепте (поле cuisine) — он главнее автоматического.
import type { Recipe } from "./types";
import { norm } from "./util";

export const CUISINES = ["Русская", "Кавказская", "Среднеазиатская", "Итальянская", "Азиатская", "Европейская", "Ближневосточная", "Американская"] as const;
export type Cuisine = (typeof CUISINES)[number];

const RULES: [Cuisine, RegExp][] = [
  ["Кавказская", /хачапур|харчо|чахохбил|лобио|табака|шашлык|хинкал|люля|сацив|аджик|ткемал|чанах|долма|кебаб|по-грузинск|по-кавказск|по-армянск|по-азербайджанск|грузинск|кавказск|пхал|чашушул|оджахур/],
  ["Среднеазиатская", /плов|манты|лагман|шурп|самс|бешбармак|по-узбекск|узбекск|казахск|чучвар|нарын|баурсак/],
  ["Итальянская", /(^|[^а-яё])паст[аеуыой](?![а-яё])|спагетт|лазань|пицц|ризотто|карбонар|болоньез|песто|моцарел|тирамису|панна[ -]?котт|брускет|фриттат|минестрон|полент|капрезе|пармезан|равиол|ньокк|по-итальянск|итальянск|фокачч|кальцоне/],
  ["Азиатская", /соев[ыо]|(^|[^а-яё])вок(?![а-яё])|фунчоз|удон|(^|[^а-яё])соба(?![а-яё])|рамен|по-китайск|по-корейск|по-японск|по-тайск|кисло-сладк|терияк|суши|ролл|кимчи|том ям|пад тай|китайск|корейск|японск|тайск|вьетнам|карри|имбир[ьн].*соус|рисов[а-я]* лапш|гречнев[а-я]* лапш/],
  ["Ближневосточная", /хумус|шакшук|фалафел|кускус|булгур|табул|баба[ -]?гануш|тахин|(^|[^а-яё])нут(?![а-яё])|шаурм|лаваш|пахлав|восточн/],
  ["Американская", /панкейк|наггетс|бургер|маффин|чизкейк|брауни|кукурузн[а-я]* хлеб|цезар|(^|[^а-яё])фри(?![а-яё])|коулслоу|хот-?дог|сэндвич|сендвич|вафл|по-американск|американск|барбекю|bbq/],
  ["Европейская", /по-французск|французск|жюльен|гратен|рататуй|киш|крем-суп|шницел|по-венгерск|гуляш|паприкаш|по-немецк|немецк|штрудел|фондю|бешамел|ростбиф|тост|омлет в духовк|крок-?месье|галет|греческ|по-гречес|паэль|гаспачо|тортиль|испанск|по-испанск|мусак|айоли|английск|бельгийск|шведск|скандинавск|голландск|кордон|ратат|суфле|мусс/],
];

/** Кухня рецепта. По умолчанию — русская (домашняя). */
export function cuisineOf(r: Recipe): Cuisine {
  if (r.cuisine && (CUISINES as readonly string[]).includes(r.cuisine)) return r.cuisine as Cuisine;
  // метку «паста» в базе ставили и макаронам по-флотски — для кухни её не учитываем
  const text = norm([r.name, ...(r.tags || []).filter((t) => norm(t) !== "паста")].join(" ")).replace(/(томатн|арахисов|шоколадн|ореховн)[а-яё]* паст[а-яё]*/g, "");
  for (const [c, re] of RULES) if (re.test(text)) return c;
  // Подсказка по продуктам: соевый соус + лапша/рис — азиатское блюдо
  const ings = norm(r.ingredients.map((i) => i.name).join(" "));
  if (/соевый соус/.test(ings) && /лапш|рис|фунчоз|имбир/.test(ings + " " + text)) return "Азиатская";
  return "Русская";
}

