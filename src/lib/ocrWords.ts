// Буквы, которые распознавание путает между собой на чековом шрифте: замена между ними «дешевле»
const LOOK = ["пл", "пн", "лн", "нм", "нк", "мн", "цд", "ра", "ию", "ил", "иы", "шщ", "ьб", "ьы", "ъь", "ео", "ес", "оа", "кх", "кж", "вб", "вз", "зэ", "гт", "ий", "ёе", "чу", "ау"];
const cheap = new Set(LOOK.flatMap((p) => [p, p[1] + p[0]]));

let vocab: { set: Set<string>; pre: Set<string>; byLen: Map<number, string[]>; n: number } | null = null;
function words() {
  if (vocab && vocab.n === CATALOG.length) return vocab;
  const set = new Set<string>(RECEIPT_WORDS.map((w) => w.replace(/ё/g, "е")));
  for (const it of CATALOG) for (const s of [it.n, ...(it.s || [])]) {
    for (const w of s.toLowerCase().replace(/ё/g, "е").split(/[^а-я]+/)) if (w.length >= 3) set.add(w);
  }
  const byLen = new Map<number, string[]>();
  // Начала слов: в чеке названия обрезаны («ГИГИЕНИЧЕ», «КАРТОФ») — такие не исправляем
  const pre = new Set<string>();
  for (const w of set) {
    const a = byLen.get(w.length) || []; a.push(w); byLen.set(w.length, a);
    for (let k = 4; k < w.length; k++) pre.add(w.slice(0, k));
  }
  vocab = { set, pre, byLen, n: CATALOG.length };
  return vocab;
}

/** Расстояние между словами: вставка/удаление/замена — 1, замена похожих букв — 0,4. Дальше limit не считаем. */
function dist(a: string, b: string, limit: number): number {
  const m = a.length, n = b.length;
  if (Math.abs(m - n) > limit) return Infinity;
  let prev = Array.from({ length: n + 1 }, (_, j) => j);
  for (let i = 1; i <= m; i++) {
    const cur = [i];
    let rowMin = i;
    for (let j = 1; j <= n; j++) {
      const c = a[i - 1] === b[j - 1] ? 0 : cheap.has(a[i - 1] + b[j - 1]) ? 0.4 : 1;
      const v = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + c);
      cur.push(v); if (v < rowMin) rowMin = v;
    }
    if (rowMin > limit) return Infinity;
    prev = cur;
  }
  return prev[n];
}

/** Одно слово: знакомое — как есть; иначе ближайшее знакомое, если оно уверенно лучше остальных. */
export function fixWord(w: string): string {
  const low = w.toLowerCase().replace(/ё/g, "е");
  if (low.length < 4 || !/^[а-я]+$/.test(low)) return w;
  const v = words();
  if (v.set.has(low) || v.pre.has(low)) return w;
  // Короткое слово — только замены похожих букв (до двух); длиннее — можно и одну обычную ошибку
  const limit = low.length <= 5 ? 0.8 : low.length <= 8 ? 1.2 : 1.6;
  let best = "", bestD = Infinity, second = Infinity;
  for (let len = low.length - 2; len <= low.length + 2; len++) {
    for (const c of v.byLen.get(len) || []) {
      const d = dist(low, c, limit);
      if (d < bestD) { second = bestD; bestD = d; best = c; } else if (d < second) second = d;
    }
  }
  if (!best || bestD > limit || second - bestD < 0.5) return w;
  // Первая буква распознаётся надёжно: меняем её только на похожую («Ц» → «Д»), но не добавляем новую («ЛЕНИНА» ≠ «ОЛЕНИНА»)
  if (best[0] !== low[0] && !cheap.has(low[0] + best[0])) return w;
  // Отличается только окончанием («ПОЗИЦИЮ» — «позиции», «СКИДКУ» — «скидка») — это то же слово в другой форме
  let same = 0;
  while (same < low.length && same < best.length && low[same] === best[same]) same++;
  if (same >= Math.min(low.length, best.length) - 2) return w;
  // Регистр как в чеке: «ЗРЛИВНОЙ» → «ЗАЛИВНОЙ», «Зрливной» → «Заливной»
  if (w === w.toUpperCase()) return best.toUpperCase();
  return w[0] === w[0].toUpperCase() ? best[0].toUpperCase() + best.slice(1) : best;
}

/** Все слова строки. */
export function fixWords(line: string): string {
  return line.replace(/[А-Яа-яЁё]+/g, (w) => fixWord(w));
}
