export function policyText(): string {
  return [POLICY_TITLE, `Версия: ${POLICY_VERSION}`, ...policySections().flatMap((s) => [`\n${s.h}`, ...s.p])].join("\n");
}

const esc = (x: string) => x.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
/** Отдельная страница для карточки магазина (public/privacy.html). */
export function policyHtml(): string {
  const body = policySections().map((s) => `<h2>${esc(s.h)}</h2>\n${s.p.map((p) => `<p>${esc(p)}</p>`).join("\n")}`).join("\n");
  return `<!doctype html>
<html lang="ru"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc(POLICY_TITLE)}</title>
<style>body{font:16px/1.5 system-ui,sans-serif;max-width:720px;margin:0 auto;padding:16px;color:#222;background:#fff}@media(prefers-color-scheme:dark){body{color:#eee;background:#161616}}h1{font-size:22px}h2{font-size:18px;margin-top:24px}</style></head>
<body><h1>${esc(POLICY_TITLE)}</h1><p>Версия: ${esc(POLICY_VERSION)}</p>
${body}
</body></html>
`;
}
