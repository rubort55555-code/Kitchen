/** Все ли источники правил существуют и у каждого правила есть источник, уровень и формулировка. */
export function rulesProblems(rules: CondRule[] = URO_RULES): string[] {
  const out: string[] = [];
  for (const r of rules) {
    if (!r.sources.length) out.push(`${r.id}: нет источника`);
    for (const s of r.sources) if (!COND_SOURCES[s]) out.push(`${r.id}: неизвестный источник ${s}`);
    if (r.sources.includes("mz2024") && !r.mzLevel) out.push(`${r.id}: не указан уровень Минздрава`);
    if (!r.quote) out.push(`${r.id}: нет формулировки из документа`);
    if (/лечени|излечи|растворит|гарант/i.test(r.title + r.app + r.why)) out.push(`${r.id}: недопустимое слово («лечение», «гарантия» и т. п.)`);
  }
  return out;
}

export interface UroStatus {
  active: boolean;
  /** Почему рекомендации не применяются (нужно показать человеку). */
  reason?: string;
  fluidLimit: boolean;
  stone: StoneType;
  /** Потолок белка 1 г/кг применяется (не применяется после 65 лет и при ИМТ ниже 18,5). */
  proteinCap: boolean;
  /** Предупреждения для плана: мочегонные, пожилой возраст. */
  warnings: string[];
}
/** Применяются ли рекомендации при мочекаменной болезни к этому человеку. */
export function uroStatus(p: BodyProfile, age: number): UroStatus {
  const c = p.conditions;
  const stone = c?.stone || "unknown";
  const base = { fluidLimit: !!c?.fluidLimit, stone, proteinCap: true, warnings: [] as string[] };
  const no = (reason: string): UroStatus => ({ ...base, active: false, reason });
  if (!c?.uro) return { ...base, active: false };
  if (age < 18) return no("Рекомендации для детей и подростков приложение не даёт: обратитесь к врачу.");
  if (p.pregnant || p.lactating) return no("При беременности и кормлении питание при мочекаменной болезни подбирает врач.");
  if (p.health?.kidney) return no("При хронической болезни почек, диализе, единственной или пересаженной почке питание подбирает врач: общие рекомендации могут навредить.");
  if (p.health?.eating) return no("При расстройстве пищевого поведения диетические ограничения не применяются: обратитесь к врачу.");
  if (c.calciumIssue) return no("При повышенном кальции в крови или гиперпаратиреозе цели по кальцию и остальные нормы подбирает врач.");
  if (c.gut) return no("После операций на желудке и кишечнике, при воспалительных болезнях кишечника и синдроме короткой кишки риск оксалатных камней иной: питание подбирает врач.");
  if (INDIVIDUAL_STONES.includes(stone)) return no("Ваш тип камней (" + STONE_TITLE[stone] + ") требует индивидуальных назначений врача. Общие нормы не применяются.");
  const bmi = p.weight / (p.height / 100) ** 2;
  const proteinCap = !(age >= 65 || bmi < 18.5);
  const warnings: string[] = [];
  if (!proteinCap) warnings.push("После 65 лет и при ИМТ ниже 18,5 потолок белка 1 г на кг не применяется: обсудите норму белка с врачом.");
  if (age >= 65) warnings.push("После 65 лет увеличивать количество жидкости нужно с осторожностью: обсудите объём с врачом.");
  if (c.diuretics) warnings.push("Вы принимаете мочегонные: при большом количестве жидкости и ограничении соли возможно опасное снижение натрия в крови; объём жидкости и соль согласуйте с врачом.");
  return { ...base, active: true, proteinCap, warnings };
}

/** Правила для карточки: по типу камней; при ограничении жидкости вместо совета пить больше — следовать врачу. */
export function rulesFor(stone: StoneType, fluidLimit = false): CondRule[] {
  return URO_RULES.filter((r) => !r.onlyFor || r.onlyFor.includes(stone)).map((r) => r.id === "fluid" && fluidLimit
    ? { ...r, title: "Жидкость: врач ограничил — следуйте его назначению", app: "Вы отметили ограничение жидкости: норму воды приложение не повышает. Объём определяет врач.", quote: "Минздрав: исключение для хронической сердечной недостаточности — объём жидкости определяет врач" }
    : r);
}

