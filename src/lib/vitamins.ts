// Витамины группы B и C (этап 4 программы биодоступности). Подсказок немного: оставлены только те, что подтверждены крупными обзорами.
// Витамин B12 есть только в продуктах животного происхождения и в обогащённых продуктах; растительное питание без добавки даёт дефицит.
// Для витамина C подсказки по способам приготовления не делаем: значения в таблицах состава даны для готового продукта, а мета-анализ
// (Kyureghian 2012) не нашёл разницы между свежими и переработанными овощами; разрозненные обзоры о потерях при варке без чисел для блюд (см. EVIDENCE_AUDIT.md).
import type { Meal } from "./types";
import type { Hint } from "./interactions";
import { sumMeals, hasMicroData } from "./diary";
import { mealParts, type IronContext } from "./iron";

const w = (src: string) => new RegExp("(?<![а-яё])(" + src + ")", "i");
/** Продукты животного происхождения — источники B12 (по названию; обогащённые продукты сюда не входят). */
const ANIMAL = w("мяс|говяд|телят|свинин|баран|ягн|кролик|индейк|куриц|курин|цыпл[её]н|утк|гус|печень(?!е)|печени|печенк|печёноч|печеноч|субпродукт|сердц|язык|рыб|лосос|сёмг|семг|форел|скумбри|сельд|тунец|треск|сайр|шпрот|килек|минтай|хек|кальмар|кревет|мидии|краб|яйц|яичн|омлет|молок|кефир|йогурт|простокваш|ряженк|сметан|сливк|творог|сыр|брынз|масло сливочное|пельмен|котлет|колбас|сосиск|ветчин|бекон|паштет|тушёнк|тушенк|фарш|бургер|стейк|шашлык|плов|борщ|бульон|окрошк|хинкали|манты");

export const B12_LOW = 1; // мкг за день: меньше — практически нет источников (норма взрослого 2,4 мкг, MR/ВОЗ ≈ 2,4)

/** День без продуктов животного происхождения и почти без B12. null — данных недостаточно или B12 в норме. */
export function b12Day(meals: Meal[], ctx: IronContext): { total: number } | null {
  if (meals.length < 2) return null;
  // Запись без данных о витаминах (своё блюдо, товар без указанных микроэлементов) — не судим: B12 мог быть, но мы его не знаем
  if (meals.some((m) => !hasMicroData(m) && !m.recipeId)) return null;
  const total = sumMeals(meals).vitB12;
  if (total >= B12_LOW) return null;
  const hasAnimal = meals.some((m) => ANIMAL.test(m.name) || mealParts(m, ctx).some((p) => ANIMAL.test(p.name)));
  if (hasAnimal) return null;
  return { total };
}

/** Ориентир ВОЗ: калия не менее 3510 мг в сутки; натрия не более 2000 мг. */
export const K_MIN = 3510;
export const NA_MAX = 2000;

/** Много натрия и мало калия за день. null — данных недостаточно (записи без данных о минералах) или всё в норме. */
export function naKDay(meals: Meal[], naMax = NA_MAX): { na: number; k: number } | null {
  if (meals.length < 2) return null;
  if (meals.some((m) => !hasMicroData(m) && !m.recipeId)) return null;
  const s = sumMeals(meals);
  return s.na > naMax && s.k < K_MIN ? { na: s.na, k: s.k } : null;
}

/** hour — час суток для сегодняшнего дня (раньше 17 ч день не закончен и упрекать рано); для прошлых дней — 24. */
export function vitaminHints(meals: Meal[], ctx: IronContext, hour = 24): Hint[] {
  const out: Hint[] = [];
  if (hour < 17) return out;
  const nk = naKDay(meals);
  if (nk) out.push({ id: "na-k", text: `Натрия ${Math.round(nk.na)} мг (выше ${NA_MAX} мг), калия ${Math.round(nk.k)} мг (ориентир ВОЗ — от ${K_MIN} мг). Больше калия дают овощи, фрукты, бобовые и картофель; в крупном испытании замена части соли на солезаменитель с калием снижала число инсультов и смертей. Солезаменители с калием нельзя при болезнях почек и некоторых лекарствах — спросите врача.`, src: ["neal2021", "wouda2022", "who2012k"] });
  const b = b12Day(meals, ctx);
  if (b) out.push({ id: "b12-plant", text: `В записях за день нет продуктов животного происхождения, витамина B12 всего ${String(Math.round(b.total * 10) / 10).replace(".", ",")} мкг (норма взрослых 2,4 мкг). B12 есть только в мясе, рыбе, яйцах, молочных и обогащённых продуктах. Если вы ограничиваете животные продукты, нужна добавка B12; по крупным обзорам у веганов без неё чаще низкий B12.`, src: ["niklewicz2024", "neufingerl2021", "pawlak2013"] });
  return out;
}
